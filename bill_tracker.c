#include <stdio.h>      // เรียกใช้ไลบรารีมาตรฐานสำหรับ input/output เช่น printf, scanf, fopen
#include <stdlib.h>     // เรียกใช้ไลบรารีสำหรับฟังก์ชันทั่วไป เช่น exit(), system()
#include <string.h>     // เรียกใช้ไลบรารีสำหรับจัดการ string เช่น strcpy, strcmp

#define MAX_RECORDS 100      // กำหนดค่าคงที่ จำนวนรายการสูงสุดที่เก็บได้ในหน่วยความจำ (array)
#define FILENAME "bills.csv" // กำหนดชื่อไฟล์ที่ใช้เก็บข้อมูลถาวร (persistent storage) เป็น .csv
#define SETTINGS_FILE "settings.csv" // ไฟล์เก็บการตั้งค่าอัตราค่าไฟ-น้ำ (โหมด + ราคาต่อหน่วยที่ผู้ใช้กำหนดเอง) แยกจากไฟล์บิล

// ===================== ตัวแปร global สำหรับตั้งค่าอัตราค่าไฟ-น้ำ =====================
// เหตุผลที่ต้องมีส่วนนี้: หอพักแต่ละที่ไม่ได้คิดค่าไฟ-น้ำตามอัตราขั้นบันไดของการไฟฟ้า/ประปาจริงๆ
// บางที่คิดเหมาเป็นราคาคงที่ต่อหน่วย (เช่น หน่วยละ 7-8 บาท) ซึ่งสูงกว่าอัตรารัฐมาก
// จึงเปิดให้ผู้ใช้เลือกได้ว่าจะคำนวณตามอัตรากรมฯ (ของจริง) หรือใส่ราคาที่หอพักเรียกเก็บเอง
// เพื่อเปรียบเทียบ/ตรวจสอบว่าหอพักคิดเกินจริงหรือไม่
int useCustomRate = 0;        // โหมดคำนวณ: 0 = ใช้อัตราขั้นบันไดของกรมไฟฟ้า/ประปา (ค่า default), 1 = ใช้อัตราที่กำหนดเอง (ตามหอพัก)
float customElecRate = 0.0;   // ราคาค่าไฟต่อหน่วยที่ผู้ใช้กำหนดเอง (บาท/หน่วย) ใช้เมื่อ useCustomRate = 1
float customWaterRate = 0.0;  // ราคาค่าน้ำต่อหน่วยที่ผู้ใช้กำหนดเอง (บาท/หน่วย) ใช้เมื่อ useCustomRate = 1

// ===================== โครงสร้างข้อมูล (struct) =====================
typedef struct {
    int month;          // เดือนที่บันทึก (1-12)
    int year;            // ปีที่บันทึก (พ.ศ. หรือ ค.ศ. ก็ได้ แล้วแต่ผู้ใช้)
    float elecOld;        // เลขมิเตอร์ไฟฟ้าครั้งก่อน (หน่วย: kWh)
    float elecNew;         // เลขมิเตอร์ไฟฟ้าครั้งล่าสุด (หน่วย: kWh)
    float waterOld;         // เลขมิเตอร์น้ำครั้งก่อน (หน่วย: ลูกบาศก์เมตร)
    float waterNew;          // เลขมิเตอร์น้ำครั้งล่าสุด (หน่วย: ลูกบาศก์เมตร)
    float elecCost;           // ค่าไฟที่คำนวณได้ (บาท) เก็บไว้ไม่ต้องคำนวณซ้ำทุกครั้ง
    float waterCost;            // ค่าน้ำที่คำนวณได้ (บาท)
    float totalCost;              // ค่าไฟ + ค่าน้ำรวมกัน (บาท)
} BillRecord;                      // ตั้งชื่อ type ว่า BillRecord เพื่อเรียกใช้ง่ายๆ แทนการพิมพ์ struct ยาวๆ

// ===================== ประกาศฟังก์ชันล่วงหน้า (prototype) =====================
float calculateElecCost(float units);              // คำนวณค่าไฟจากจำนวนหน่วยที่ใช้ แบบขั้นบันได
float calculateWaterCost(float units);              // คำนวณค่าน้ำจากจำนวนหน่วยที่ใช้ แบบขั้นบันได
void addNewRecord(BillRecord records[], int *count); // เพิ่มรายการใหม่ 1 เดือน แล้วอัปเดต count
void saveToFile(BillRecord records[], int count);     // เขียนข้อมูลทั้งหมดใน array ลงไฟล์ (เขียนทับทุกครั้ง)
int loadFromFile(BillRecord records[]);                // อ่านข้อมูลจากไฟล์เข้ามาเก็บใน array ตอนเปิดโปรแกรม
void showHistory(BillRecord records[], int count);      // แสดงประวัติย้อนหลังทั้งหมดเป็นตาราง
void showStatistics(BillRecord records[], int count);    // คำนวณและแสดงค่าเฉลี่ย/สูงสุด/ต่ำสุด
void splitBill(BillRecord records[], int count);          // หารค่าใช้จ่ายเดือนล่าสุดตามจำนวนคน
void showMenu();                                            // แสดงเมนูหลักบนหน้าจอ
void setCustomRates();                                       // เมนูตั้งค่าอัตราค่าไฟ-น้ำ (เลือกโหมด + กรอกราคาต่อหน่วยของหอพัก)
void loadSettings();                                          // โหลดการตั้งค่าอัตรา (โหมด/ราคา) จากไฟล์ตอนเปิดโปรแกรม
void saveSettings();                                            // บันทึกการตั้งค่าอัตราลงไฟล์ทุกครั้งที่มีการเปลี่ยน

// ===================== ฟังก์ชันหลัก main() =====================
int main() {
    #ifdef _WIN32                              // ตรวจสอบว่ากำลังคอมไพล์บน Windows หรือไม่ (macro นี้ถูกกำหนดอัตโนมัติเฉพาะบน Windows)
        system("chcp 65001 > nul");              // สั่งให้ terminal เปลี่ยน code page เป็น UTF-8 (65001) เพื่อให้แสดงภาษาไทยถูกต้อง แล้วซ่อนข้อความผลลัพธ์ของคำสั่งด้วย > nul
    #endif                                        // ปิดเงื่อนไข #ifdef เฉพาะโค้ดนี้จะถูกคอมไพล์เมื่อ target เป็น Windows เท่านั้น ระบบอื่นจะข้ามส่วนนี้ไปเลย

    BillRecord records[MAX_RECORDS]; // ประกาศ array สำหรับเก็บข้อมูลบิลทุกเดือน สูงสุด 100 รายการ ในหน่วยความจำ (RAM)
    int count = loadFromFile(records); // โหลดข้อมูลเก่าจากไฟล์มาใส่ array ตั้งแต่เปิดโปรแกรม แล้วเก็บจำนวนรายการไว้ที่ count
    loadSettings();                     // โหลดการตั้งค่าอัตราค่าไฟ-น้ำ (โหมด + ราคาที่เคยตั้งไว้) จากไฟล์ settings.csv ถ้ามี
    int choice;                         // ตัวแปรเก็บตัวเลขเมนูที่ผู้ใช้เลือก

    do {                                  // เริ่มลูป do-while เพื่อวนแสดงเมนูจนกว่าผู้ใช้จะเลือกออก
        showMenu();                        // เรียกฟังก์ชันแสดงเมนูตัวเลือกทั้งหมด
        printf("เลือกเมนู: ");                // พิมพ์ข้อความถามผู้ใช้ว่าต้องการเมนูไหน
        scanf("%d", &choice);                  // รับค่าตัวเลขจากผู้ใช้ เก็บลงตัวแปร choice

        switch (choice) {                        // ใช้ switch-case แยกการทำงานตามเมนูที่เลือก
            case 1:                                // ถ้าเลือกเมนู 1
                addNewRecord(records, &count);       // เรียกฟังก์ชันเพิ่มข้อมูลบิลเดือนใหม่ ส่ง array และ pointer ของ count ไปแก้ไขได้จริง
                saveToFile(records, count);           // บันทึกข้อมูลทั้งหมดลงไฟล์ทันที เพื่อไม่ให้ข้อมูลหายถ้าปิดโปรแกรม
                break;                                  // จบ case นี้ ออกจาก switch
            case 2:                                      // ถ้าเลือกเมนู 2
                showHistory(records, count);               // เรียกฟังก์ชันแสดงประวัติย้อนหลังทั้งหมด
                break;                                        // จบ case นี้
            case 3:                                            // ถ้าเลือกเมนู 3
                showStatistics(records, count);                  // เรียกฟังก์ชันแสดงสถิติสรุป (เฉลี่ย/สูงสุด/ต่ำสุด)
                break;                                              // จบ case นี้
            case 4:                                                // ถ้าเลือกเมนู 4
                splitBill(records, count);                           // เรียกฟังก์ชันหารค่าใช้จ่ายกับเพื่อนร่วมห้อง
                break;                                                  // จบ case นี้
            case 5:                                                // ถ้าเลือกเมนู 5 (ตั้งค่าอัตราค่าไฟ-น้ำเอง)
                setCustomRates();                                     // เรียกฟังก์ชันให้ผู้ใช้เลือกโหมด + กรอกราคาต่อหน่วยของหอพัก
                break;                                                  // จบ case นี้ (ฟังก์ชันนี้ save settings ให้เองข้างในแล้ว)
            case 6:                                                    // ถ้าเลือกเมนู 6 (ออกจากโปรแกรม)
                printf("ขอบคุณที่ใช้งานโปรแกรม\n");                       // พิมพ์ข้อความอำลาผู้ใช้
                break;                                                     // จบ case นี้ แล้วลูปจะจบเพราะเงื่อนไข while ด้านล่าง
            default:                                                       // ถ้าผู้ใช้พิมพ์ตัวเลขที่ไม่มีในเมนู
                printf("กรุณาเลือกเมนูให้ถูกต้อง\n");                          // แจ้งเตือนให้เลือกใหม่
        }                                                                       // ปิด switch
        printf("\n");                                                            // เว้นบรรทัดว่างให้อ่านง่ายขึ้นก่อนวนเมนูรอบใหม่
    } while (choice != 6);                                                          // วนลูปซ้ำจนกว่าผู้ใช้จะเลือกเมนู 6 (ออก)

    return 0;                                                                          // จบโปรแกรม คืนค่า 0 หมายถึงทำงานสำเร็จไม่มี error
}

// ===================== แสดงเมนูหลัก =====================
void showMenu() {
    printf("==== ระบบคำนวณค่าไฟ-น้ำรายเดือน ====\n"); // หัวข้อเมนู ใช้ \n ขึ้นบรรทัดใหม่
    // แสดงโหมดอัตราปัจจุบันไว้บนสุดของเมนู เพื่อให้ผู้ใช้เห็นตลอดว่าตอนนี้กำลังคิดราคาแบบไหนอยู่
    if (useCustomRate) {                                                          // ถ้ากำลังใช้อัตราที่กำหนดเอง (ตามหอพัก)
        printf("[โหมดปัจจุบัน: อัตราตามหอพัก -> ไฟ %.2f บาท/หน่วย, น้ำ %.2f บาท/หน่วย]\n",
               customElecRate, customWaterRate);                                     // โชว์ราคาที่ตั้งไว้ให้เห็นชัดๆ
    } else {                                                                        // ถ้ายังใช้อัตรากรมฯ แบบขั้นบันได (ค่า default)
        printf("[โหมดปัจจุบัน: อัตรากรมไฟฟ้า/ประปา (ขั้นบันได)]\n");                       // แจ้งว่ากำลังใช้อัตรามาตรฐาน
    }
    printf("1. บันทึกข้อมูลเดือนใหม่\n");                 // ตัวเลือกที่ 1
    printf("2. ดูประวัติย้อนหลัง\n");                       // ตัวเลือกที่ 2
    printf("3. ดูสถิติสรุป\n");                               // ตัวเลือกที่ 3
    printf("4. หารค่าใช้จ่ายกับเพื่อนร่วมห้อง\n");                // ตัวเลือกที่ 4
    printf("5. ตั้งค่าอัตราค่าไฟ-น้ำ (กรมฯ หรือหอพักกำหนดเอง)\n");   // ตัวเลือกที่ 5 (ใหม่)
    printf("6. ออกจากโปรแกรม\n");                                // ตัวเลือกที่ 6
}

// ===================== คำนวณค่าไฟแบบขั้นบันได =====================
float calculateElecCost(float units) {  // รับพารามิเตอร์ units คือจำนวนหน่วยไฟที่ใช้ไปในเดือนนั้น
    float cost = 0;                       // ตัวแปรเก็บค่าไฟสะสม เริ่มต้นที่ 0
    if (units <= 150) {                     // ถ้าใช้ไม่เกิน 150 หน่วย (ขั้นที่ 1)
        cost = units * 3.24;                  // คิดราคาหน่วยละ 3.24 บาท ทั้งหมด
    } else if (units <= 400) {                  // ถ้าใช้มากกว่า 150 แต่ไม่เกิน 400 หน่วย (ขั้นที่ 2)
        cost = 150 * 3.24;                         // 150 หน่วยแรกคิดราคาขั้นที่ 1 ก่อน
        cost += (units - 150) * 4.22;                // ส่วนที่เกิน 150 หน่วย คิดราคาหน่วยละ 4.22 บาท แล้วบวกเพิ่ม
    } else {                                            // ถ้าใช้เกิน 400 หน่วย (ขั้นที่ 3)
        cost = 150 * 3.24;                                // 150 หน่วยแรก คิดราคาขั้นที่ 1
        cost += 250 * 4.22;                                 // 250 หน่วยถัดมา (151-400) คิดราคาขั้นที่ 2
        cost += (units - 400) * 4.42;                         // ส่วนที่เกิน 400 หน่วย คิดราคาหน่วยละ 4.42 บาท
    }
    return cost;                                                // ส่งค่าค่าไฟที่คำนวณได้ทั้งหมดกลับไปยังผู้เรียกใช้ฟังก์ชัน
}

// ===================== คำนวณค่าน้ำแบบขั้นบันได =====================
float calculateWaterCost(float units) {  // รับพารามิเตอร์ units คือจำนวนหน่วยน้ำที่ใช้ไปในเดือนนั้น (ลบ.ม.)
    float cost = 0;                        // ตัวแปรเก็บค่าน้ำสะสม เริ่มต้นที่ 0
    if (units <= 10) {                       // ถ้าใช้ไม่เกิน 10 หน่วย (ขั้นที่ 1)
        cost = units * 10.0;                   // คิดราคาหน่วยละ 10 บาท
    } else if (units <= 30) {                    // ถ้าใช้มากกว่า 10 แต่ไม่เกิน 30 หน่วย (ขั้นที่ 2)
        cost = 10 * 10.0;                          // 10 หน่วยแรกคิดราคาขั้นที่ 1
        cost += (units - 10) * 15.0;                 // ส่วนที่เกิน 10 หน่วย คิดราคาหน่วยละ 15 บาท
    } else {                                            // ถ้าใช้เกิน 30 หน่วย (ขั้นที่ 3)
        cost = 10 * 10.0;                                 // 10 หน่วยแรก คิดราคาขั้นที่ 1
        cost += 20 * 15.0;                                  // 20 หน่วยถัดมา (11-30) คิดราคาขั้นที่ 2
        cost += (units - 30) * 20.0;                          // ส่วนที่เกิน 30 หน่วย คิดราคาหน่วยละ 20 บาท
    }
    return cost;                                                // ส่งค่าค่าน้ำที่คำนวณได้ทั้งหมดกลับไปยังผู้เรียกใช้ฟังก์ชัน
}

// ===================== เพิ่มรายการบิลใหม่ =====================
void addNewRecord(BillRecord records[], int *count) { // รับ array ของบิล และ pointer ของ count เพื่อแก้ไขค่าจริงได้ (pass by reference)
    if (*count >= MAX_RECORDS) {                          // ตรวจสอบว่าจำนวนรายการเต็มความจุ array แล้วหรือยัง
        printf("บันทึกข้อมูลเต็มแล้ว ไม่สามารถเพิ่มได้\n");        // แจ้งเตือนถ้าเต็ม
        return;                                                // ออกจากฟังก์ชันทันที ไม่ทำงานต่อ
    }

    BillRecord r;                                              // สร้างตัวแปร struct ชั่วคราวสำหรับเก็บข้อมูลที่กำลังจะกรอก

    printf("กรอกเดือน (1-12): ");                                // ถามเดือน
    scanf("%d", &r.month);                                        // รับค่าเดือนเก็บใน r.month

    printf("กรอกปี: ");                                            // ถามปี
    scanf("%d", &r.year);                                            // รับค่าปีเก็บใน r.year

    printf("เลขมิเตอร์ไฟครั้งก่อน: ");                                  // ถามเลขมิเตอร์ไฟเก่า
    scanf("%f", &r.elecOld);                                            // รับค่าทศนิยม เก็บใน r.elecOld

    printf("เลขมิเตอร์ไฟครั้งล่าสุด: ");                                   // ถามเลขมิเตอร์ไฟใหม่
    scanf("%f", &r.elecNew);                                               // รับค่าเก็บใน r.elecNew

    printf("เลขมิเตอร์น้ำครั้งก่อน: ");                                       // ถามเลขมิเตอร์น้ำเก่า
    scanf("%f", &r.waterOld);                                                  // รับค่าเก็บใน r.waterOld

    printf("เลขมิเตอร์น้ำครั้งล่าสุด: ");                                         // ถามเลขมิเตอร์น้ำใหม่
    scanf("%f", &r.waterNew);                                                      // รับค่าเก็บใน r.waterNew

    float elecUnits = r.elecNew - r.elecOld;    // คำนวณหน่วยไฟที่ใช้ไป = เลขใหม่ - เลขเก่า
    float waterUnits = r.waterNew - r.waterOld;   // คำนวณหน่วยน้ำที่ใช้ไป = เลขใหม่ - เลขเก่า

    // ===== จุดสำคัญ: เลือกวิธีคำนวณตามโหมดที่ผู้ใช้ตั้งไว้ (เมนู 5) =====
    // เพราะหอพักแต่ละที่ไม่ได้คิดราคาตามอัตราขั้นบันไดของรัฐจริงๆ บางที่เหมาราคาคงที่ต่อหน่วยเอง
    if (useCustomRate) {                                       // ถ้าผู้ใช้ตั้งค่าให้ใช้อัตราของหอพัก (ราคาคงที่/หน่วย)
        r.elecCost = elecUnits * customElecRate;                  // ค่าไฟ = หน่วยที่ใช้ x ราคาที่หอพักเรียกเก็บต่อหน่วย
        r.waterCost = waterUnits * customWaterRate;                 // ค่าน้ำ = หน่วยที่ใช้ x ราคาที่หอพักเรียกเก็บต่อหน่วย
    } else {                                                       // ถ้ายังใช้อัตรากรมไฟฟ้า/ประปาแบบขั้นบันได (ค่า default)
        r.elecCost = calculateElecCost(elecUnits);                   // เรียกฟังก์ชันคำนวณค่าไฟแบบขั้นบันไดของจริง
        r.waterCost = calculateWaterCost(waterUnits);                  // เรียกฟังก์ชันคำนวณค่าน้ำแบบขั้นบันไดของจริง
    }
    r.totalCost = r.elecCost + r.waterCost;             // รวมค่าไฟและค่าน้ำเข้าด้วยกัน เก็บใน r.totalCost

    records[*count] = r;      // นำข้อมูล r ที่กรอกครบแล้ว ไปเก็บใน array ตำแหน่งล่าสุด (index = count ปัจจุบัน)
    (*count)++;                 // เพิ่มจำนวนรายการขึ้น 1 เพราะเพิ่งเพิ่มข้อมูลใหม่ (ใช้ * เพราะ count เป็น pointer)

    printf("\n--- สรุปผล ---\n");                              // หัวข้อสรุปผลการคำนวณ
    printf("โหมดที่ใช้คำนวณ: %s\n", useCustomRate ? "อัตราตามหอพัก (กำหนดเอง)" : "อัตรากรมไฟฟ้า/ประปา (ขั้นบันได)"); // แจ้งให้เห็นชัดว่าใช้เกณฑ์ไหนคำนวณ ป้องกันสับสน
    printf("หน่วยไฟที่ใช้: %.2f kWh\n", elecUnits);                // แสดงหน่วยไฟที่ใช้ ทศนิยม 2 ตำแหน่ง
    printf("หน่วยน้ำที่ใช้: %.2f ลบ.ม.\n", waterUnits);              // แสดงหน่วยน้ำที่ใช้
    printf("ค่าไฟ: %.2f บาท\n", r.elecCost);                        // แสดงค่าไฟที่คำนวณได้
    printf("ค่าน้ำ: %.2f บาท\n", r.waterCost);                        // แสดงค่าน้ำที่คำนวณได้
    printf("รวมทั้งหมด: %.2f บาท\n", r.totalCost);                     // แสดงยอดรวมทั้งหมด
    printf("บันทึกข้อมูลเรียบร้อย\n");                                    // แจ้งว่าบันทึกสำเร็จ (จริงๆ จะเซฟไฟล์ที่ main หลังเรียกฟังก์ชันนี้)
}

// ===================== บันทึกข้อมูลทั้งหมดลงไฟล์ =====================
void saveToFile(BillRecord records[], int count) { // รับ array ของบิลทั้งหมด และจำนวนรายการปัจจุบัน
    FILE *fp = fopen(FILENAME, "w");                  // เปิดไฟล์ในโหมด "w" (write) เขียนทับของเดิมทั้งหมดทุกครั้งที่เรียก
    if (fp == NULL) {                                    // ตรวจสอบว่าเปิดไฟล์สำเร็จหรือไม่ (เช่น ไม่มีสิทธิ์เขียน)
        printf("ไม่สามารถเปิดไฟล์เพื่อบันทึกได้\n");           // แจ้งเตือนถ้าเปิดไฟล์ไม่สำเร็จ
        return;                                                // ออกจากฟังก์ชันทันที
    }

    for (int i = 0; i < count; i++) {                          // วนลูปตามจำนวนรายการทั้งหมดใน array
        fprintf(fp, "%d,%d,%.2f,%.2f,%.2f,%.2f,%.2f,%.2f,%.2f\n", // เขียนข้อมูลแต่ละแถวลงไฟล์ คั่นด้วยจุลภาค (รูปแบบ CSV)
                records[i].month, records[i].year,                   // เดือน, ปี
                records[i].elecOld, records[i].elecNew,                // เลขมิเตอร์ไฟเก่า, ใหม่
                records[i].waterOld, records[i].waterNew,                // เลขมิเตอร์น้ำเก่า, ใหม่
                records[i].elecCost, records[i].waterCost,                 // ค่าไฟ, ค่าน้ำ
                records[i].totalCost);                                       // ยอดรวม
    }

    fclose(fp);   // ปิดไฟล์หลังเขียนเสร็จ เพื่อบันทึกข้อมูลลงดิสก์จริงๆ (flush buffer)
}

// ===================== โหลดข้อมูลจากไฟล์ตอนเปิดโปรแกรม =====================
int loadFromFile(BillRecord records[]) { // รับ array เปล่าเพื่อนำข้อมูลจากไฟล์มาใส่
    FILE *fp = fopen(FILENAME, "r");        // เปิดไฟล์ในโหมด "r" (read) เพื่ออ่านข้อมูลเดิม
    int count = 0;                            // ตัวแปรนับจำนวนรายการที่อ่านได้ เริ่มที่ 0

    if (fp == NULL) {                           // ถ้าเปิดไฟล์ไม่ได้ (เช่น รันโปรแกรมครั้งแรก ยังไม่มีไฟล์)
        return 0;                                 // คืนค่า 0 หมายถึงยังไม่มีข้อมูลเก่าเลย ไม่ถือเป็น error
    }

    while (fscanf(fp, "%d,%d,%f,%f,%f,%f,%f,%f,%f", // อ่านข้อมูลทีละแถวตามรูปแบบเดียวกับตอนเขียน (CSV)
                  &records[count].month, &records[count].year,  // อ่านเดือน, ปี ใส่ตำแหน่ง count ปัจจุบัน
                  &records[count].elecOld, &records[count].elecNew, // อ่านเลขมิเตอร์ไฟเก่า, ใหม่
                  &records[count].waterOld, &records[count].waterNew, // อ่านเลขมิเตอร์น้ำเก่า, ใหม่
                  &records[count].elecCost, &records[count].waterCost, // อ่านค่าไฟ, ค่าน้ำที่เคยคำนวณไว้
                  &records[count].totalCost) == 9) {                    // ตรวจว่าอ่านครบ 9 ค่าตามที่กำหนดหรือไม่ ถ้าครบถือว่าอ่านแถวนี้สำเร็จ
        count++;                                                           // ถ้าอ่านสำเร็จ เพิ่มตัวนับรายการขึ้น 1
        if (count >= MAX_RECORDS) break;                                     // ถ้าเต็มความจุ array แล้ว หยุดอ่านทันทีป้องกัน array overflow
    }

    fclose(fp);        // ปิดไฟล์หลังอ่านเสร็จ
    return count;         // คืนค่าจำนวนรายการทั้งหมดที่อ่านได้ กลับไปเก็บไว้ที่ตัวแปร count ใน main()
}

// ===================== แสดงประวัติย้อนหลังทั้งหมด =====================
void showHistory(BillRecord records[], int count) { // รับ array และจำนวนรายการที่มีอยู่จริง
    if (count == 0) {                                  // ถ้ายังไม่มีข้อมูลเลย
        printf("ยังไม่มีข้อมูลบันทึกไว้\n");                 // แจ้งเตือนว่าไม่มีประวัติ
        return;                                            // ออกจากฟังก์ชัน ไม่ต้องแสดงตารางเปล่า
    }

    printf("\n%-6s %-6s %-10s %-10s %-10s\n", "เดือน", "ปี", "ค่าไฟ", "ค่าน้ำ", "รวม"); // พิมพ์หัวตาราง จัดคอลัมน์ด้วย %-Ns (ชิดซ้าย กว้าง N ตัวอักษร)
    for (int i = 0; i < count; i++) {                                                   // วนลูปแสดงข้อมูลทีละแถวตามจำนวนรายการทั้งหมด
        printf("%-6d %-6d %-10.2f %-10.2f %-10.2f\n",                                      // พิมพ์แต่ละแถวด้วยรูปแบบเดียวกับหัวตาราง
               records[i].month, records[i].year,                                             // เดือน, ปี ของแถวนั้น
               records[i].elecCost, records[i].waterCost, records[i].totalCost);               // ค่าไฟ, ค่าน้ำ, ยอดรวมของแถวนั้น
    }
}

// ===================== แสดงสถิติสรุป =====================
void showStatistics(BillRecord records[], int count) { // รับ array และจำนวนรายการ
    if (count == 0) {                                     // ถ้าไม่มีข้อมูลเลย
        printf("ยังไม่มีข้อมูลสำหรับคำนวณสถิติ\n");             // แจ้งเตือน
        return;                                                // ออกจากฟังก์ชัน
    }

    float sum = 0;                        // ตัวแปรเก็บผลรวมค่าใช้จ่ายทั้งหมด เริ่มที่ 0
    float maxCost = records[0].totalCost;   // ตัวแปรเก็บค่าสูงสุด เริ่มต้นด้วยค่าของรายการแรก
    float minCost = records[0].totalCost;     // ตัวแปรเก็บค่าต่ำสุด เริ่มต้นด้วยค่าของรายการแรกเช่นกัน
    int maxMonth = records[0].month, maxYear = records[0].year; // เก็บเดือน/ปีของรายการที่ใช้จ่ายสูงสุด
    int minMonth = records[0].month, minYear = records[0].year;   // เก็บเดือน/ปีของรายการที่ใช้จ่ายต่ำสุด

    for (int i = 0; i < count; i++) {              // วนลูปตรวจสอบทุกรายการ
        sum += records[i].totalCost;                  // บวกยอดรวมของแต่ละเดือนเข้าไปใน sum เรื่อยๆ
        if (records[i].totalCost > maxCost) {           // ถ้าพบค่าที่มากกว่า maxCost ปัจจุบัน
            maxCost = records[i].totalCost;                // อัปเดตค่าสูงสุดใหม่
            maxMonth = records[i].month;                     // จำเดือนของรายการนั้นไว้
            maxYear = records[i].year;                         // จำปีของรายการนั้นไว้
        }
        if (records[i].totalCost < minCost) {                    // ถ้าพบค่าที่น้อยกว่า minCost ปัจจุบัน
            minCost = records[i].totalCost;                         // อัปเดตค่าต่ำสุดใหม่
            minMonth = records[i].month;                              // จำเดือนของรายการนั้นไว้
            minYear = records[i].year;                                  // จำปีของรายการนั้นไว้
        }
    }

    float avg = sum / count;    // คำนวณค่าเฉลี่ย = ผลรวมทั้งหมด หารด้วยจำนวนรายการ

    printf("\n--- สถิติสรุป ---\n");                                     // หัวข้อสถิติ
    printf("ค่าใช้จ่ายเฉลี่ยต่อเดือน: %.2f บาท\n", avg);                       // แสดงค่าเฉลี่ย
    printf("เดือนที่ใช้จ่ายสูงสุด: %d/%d (%.2f บาท)\n", maxMonth, maxYear, maxCost); // แสดงเดือน/ปี/ยอดของเดือนที่จ่ายมากสุด
    printf("เดือนที่ใช้จ่ายต่ำสุด: %d/%d (%.2f บาท)\n", minMonth, minYear, minCost);   // แสดงเดือน/ปี/ยอดของเดือนที่จ่ายน้อยสุด

    printf("\nกราฟเปรียบเทียบค่าใช้จ่ายแต่ละเดือน:\n");   // หัวข้อกราฟแท่งอย่างง่าย
    for (int i = 0; i < count; i++) {                       // วนลูปแสดงกราฟทุกเดือน
        printf("%d/%d: ", records[i].month, records[i].year);  // แสดงเดือน/ปีนำหน้าแท่งกราฟ
        int bars = (int)(records[i].totalCost / 50);              // แปลงยอดเงินเป็นจำนวนแท่ง โดยหาร 50 (ปรับสเกลได้ตามต้องการ)
        for (int j = 0; j < bars; j++) {                              // วนลูปพิมพ์เครื่องหมาย * ตามจำนวน bars
            printf("*");                                                 // พิมพ์แท่งกราฟทีละตัว ไม่ขึ้นบรรทัดใหม่
        }
        printf(" (%.2f บาท)\n", records[i].totalCost);                     // พิมพ์ยอดเงินจริงต่อท้ายแท่งกราฟ แล้วขึ้นบรรทัดใหม่
    }
}

// ===================== หารค่าใช้จ่ายกับเพื่อนร่วมห้อง =====================
void splitBill(BillRecord records[], int count) { // รับ array และจำนวนรายการทั้งหมด
    if (count == 0) {                                // ถ้ายังไม่มีข้อมูลเลย
        printf("ยังไม่มีข้อมูลให้หารค่าใช้จ่าย\n");         // แจ้งเตือน
        return;                                          // ออกจากฟังก์ชัน
    }

    BillRecord latest = records[count - 1]; // ดึงรายการล่าสุด (index สุดท้าย) มาเก็บไว้ในตัวแปร latest เพื่อใช้หาร
    int people;                                // ตัวแปรเก็บจำนวนคนที่จะหารค่าใช้จ่าย

    printf("บิลล่าสุดคือเดือน %d/%d รวม %.2f บาท\n", latest.month, latest.year, latest.totalCost); // แสดงข้อมูลบิลล่าสุดให้ผู้ใช้เห็นก่อนหาร
    printf("จำนวนคนที่ร่วมหารค่าใช้จ่าย: ");                                                          // ถามจำนวนคน
    scanf("%d", &people);                                                                               // รับค่าจำนวนคนจากผู้ใช้

    if (people <= 0) {                                    // ตรวจสอบว่าจำนวนคนต้องมากกว่า 0 เท่านั้น (ป้องกันหารด้วย 0 หรือค่าติดลบ)
        printf("จำนวนคนต้องมากกว่า 0\n");                     // แจ้งเตือนถ้ากรอกผิด
        return;                                                 // ออกจากฟังก์ชันทันที ไม่คำนวณต่อ
    }

    float perPerson = latest.totalCost / people; // คำนวณค่าใช้จ่ายต่อคน = ยอดรวม หารด้วยจำนวนคน
    printf("แต่ละคนต้องจ่ายคนละ: %.2f บาท\n", perPerson); // แสดงผลลัพธ์ค่าใช้จ่ายต่อคน
}

// ===================== ตั้งค่าอัตราค่าไฟ-น้ำ (เมนู 5) =====================
// ฟังก์ชันนี้ให้ผู้ใช้เลือกว่าจะคำนวณบิลด้วยอัตราแบบไหน:
//   1) อัตรากรมไฟฟ้า/ประปาจริง (ขั้นบันได) - ใช้ในกรณีอยู่บ้าน/คอนโดที่จ่ายตรงกับการไฟฟ้า
//   2) อัตราที่หอพักกำหนดเอง (ราคาคงที่ต่อหน่วย) - ใช้ในกรณีอยู่หอพักที่เหมาราคาเอง ซึ่งมักจะสูงกว่าอัตรารัฐ
// การมีทั้งสองโหมดช่วยให้ผู้ใช้เปรียบเทียบได้ว่าหอพักคิดราคาสมเหตุสมผลหรือไม่
void setCustomRates() {
    int mode; // ตัวแปรเก็บโหมดที่ผู้ใช้เลือกชั่วคราวก่อนนำไปใส่ตัวแปร global

    printf("\n--- ตั้งค่าอัตราค่าไฟ-น้ำ ---\n");                         // หัวข้อเมนูย่อย
    printf("1. ใช้อัตรากรมไฟฟ้า/ประปา (คำนวณแบบขั้นบันไดตามจริง)\n");        // ตัวเลือกที่ 1
    printf("2. ใช้อัตราตามหอพัก (กำหนดราคาต่อหน่วยเอง)\n");                  // ตัวเลือกที่ 2
    printf("เลือกโหมด: ");                                                // ถามผู้ใช้
    scanf("%d", &mode);                                                     // รับค่าโหมดที่เลือก

    if (mode == 2) {                                              // ถ้าเลือกโหมดหอพัก (กำหนดราคาเอง)
        useCustomRate = 1;                                           // ตั้งสถานะ global ว่ากำลังใช้อัตราแบบกำหนดเอง

        printf("กรอกราคาค่าไฟที่หอพักคิด (บาท/หน่วย): ");                  // ถามราคาค่าไฟต่อหน่วยที่หอเรียกเก็บจริง
        scanf("%f", &customElecRate);                                        // รับค่าราคาไฟ เก็บใน customElecRate

        printf("กรอกราคาค่าน้ำที่หอพักคิด (บาท/หน่วย): ");                  // ถามราคาค่าน้ำต่อหน่วยที่หอเรียกเก็บจริง
        scanf("%f", &customWaterRate);                                        // รับค่าราคาน้ำ เก็บใน customWaterRate

        printf("ตั้งค่าเรียบร้อย: ไฟ %.2f บาท/หน่วย, น้ำ %.2f บาท/หน่วย\n",
               customElecRate, customWaterRate);                                // ยืนยันค่าที่ตั้งให้ผู้ใช้เห็น
    } else if (mode == 1) {                                        // ถ้าเลือกโหมดอัตรากรมฯ (กลับไปใช้ขั้นบันไดของจริง)
        useCustomRate = 0;                                            // ตั้งสถานะ global กลับเป็นโหมดมาตรฐาน
        printf("ตั้งค่าเรียบร้อย: ใช้อัตรากรมไฟฟ้า/ประปา (ขั้นบันได)\n");        // แจ้งผลลัพธ์
    } else {                                                        // ถ้ากรอกตัวเลือกที่ไม่มีในเมนู
        printf("กรุณาเลือก 1 หรือ 2 เท่านั้น ไม่มีการเปลี่ยนแปลงค่าเดิม\n");     // แจ้งเตือน ไม่แก้ไขอะไร
        return;                                                        // ออกจากฟังก์ชันเลย ไม่ต้อง save ซ้ำ
    }

    saveSettings(); // บันทึกการตั้งค่าล่าสุดลงไฟล์ทันที เพื่อให้ครั้งหน้าเปิดโปรแกรมมาแล้วยังจำโหมด/ราคาเดิมได้
}

// ===================== โหลดการตั้งค่าอัตราจากไฟล์ตอนเปิดโปรแกรม =====================
void loadSettings() {
    FILE *fp = fopen(SETTINGS_FILE, "r");  // เปิดไฟล์ settings.csv โหมดอ่าน

    if (fp == NULL) {                        // ถ้ายังไม่เคยมีไฟล์นี้มาก่อน (เปิดโปรแกรมครั้งแรก)
        useCustomRate = 0;                      // ตั้งค่า default: ใช้อัตรากรมฯ
        customElecRate = 0.0;                     // ราคากำหนดเองยังไม่มี ตั้งเป็น 0 ไว้ก่อน
        customWaterRate = 0.0;                      // เช่นเดียวกันกับค่าน้ำ
        return;                                       // ออกจากฟังก์ชัน ไม่ถือเป็น error
    }

    // อ่านค่า 3 ค่าตามรูปแบบที่ saveSettings เขียนไว้: โหมด,ราคาไฟ,ราคาน้ำ
    if (fscanf(fp, "%d,%f,%f", &useCustomRate, &customElecRate, &customWaterRate) != 3) {
        // ถ้าอ่านไม่ครบ 3 ค่า (ไฟล์เพี้ยน/ว่างเปล่า) ให้ย้อนกลับไปใช้ค่า default เพื่อความปลอดภัย
        useCustomRate = 0;    // กลับไปใช้อัตรากรมฯ
        customElecRate = 0.0;   // เคลียร์ค่าไฟที่กำหนดเอง
        customWaterRate = 0.0;    // เคลียร์ค่าน้ำที่กำหนดเอง
    }

    fclose(fp); // ปิดไฟล์หลังอ่านเสร็จ
}

// ===================== บันทึกการตั้งค่าอัตราลงไฟล์ =====================
void saveSettings() {
    FILE *fp = fopen(SETTINGS_FILE, "w"); // เปิดไฟล์ settings.csv โหมดเขียน (เขียนทับค่าเดิมทุกครั้ง)
    if (fp == NULL) {                        // ถ้าเปิดไฟล์ไม่สำเร็จ (เช่น ไม่มีสิทธิ์เขียนไฟล์)
        printf("ไม่สามารถบันทึกการตั้งค่าได้\n"); // แจ้งเตือนผู้ใช้
        return;                                    // ออกจากฟังก์ชันทันที
    }

    fprintf(fp, "%d,%.2f,%.2f\n", useCustomRate, customElecRate, customWaterRate); // เขียนโหมด+ราคาไฟ+ราคาน้ำ ลงไฟล์บรรทัดเดียว
    fclose(fp); // ปิดไฟล์เพื่อบันทึกข้อมูลลงดิสก์จริงๆ
}